#!/usr/bin/env node

// Regenerates the static project/skill fallback embedded in index.html.
// The fallback keeps the content readable for clients that do not execute
// JavaScript (search engines, LLM fetchers, terminal browsers). The regular
// page still renders from data/data.json and switches languages at runtime.
//
// Usage: node scripts/build-static.js

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.resolve(__dirname, '..');
const indexPath = path.join(root, 'index.html');
const dataPath = path.join(root, 'data', 'data.json');
const scriptPath = path.join(root, 'scripts', 'script.js');

const data = JSON.parse(fs.readFileSync(dataPath, 'utf8'));

const grids = new Map();
const noop = () => {};

function getGrid(id) {
  if (!grids.has(id)) {
    grids.set(id, {
      innerHTML: '',
      classList: { add: noop, remove: noop },
      dataset: {}
    });
  }
  return grids.get(id);
}

const documentMock = {
  addEventListener: noop,
  querySelectorAll: () => [],
  querySelector: () => null,
  getElementById: getGrid,
  createElement: () => ({ style: {}, setAttribute: noop, select: noop }),
  documentElement: { classList: { add: noop, remove: noop } },
  body: { appendChild: noop, removeChild: noop },
  execCommand: () => true
};

const windowMock = {
  addEventListener: noop,
  innerHeight: 0,
  isSecureContext: false,
  matchMedia: () => ({ matches: false })
};

const context = {
  document: documentMock,
  window: windowMock,
  localStorage: { getItem: () => null, setItem: noop },
  navigator: {},
  console,
  fetch: async () => ({ json: async () => ({}) })
};

vm.createContext(context);
vm.runInContext(fs.readFileSync(scriptPath, 'utf8'), context, { filename: 'script.js' });

context.renderSkills(data.skills, 'en');
context.renderProjects(data.projects, 'en', 'projects-grid');
context.renderProjects(data.archivedProjects || [], 'en', 'archive-grid');

function dedent(text) {
  const lines = text.replace(/\s+$/g, '').split('\n');
  const indents = lines
    .filter(line => line.trim())
    .map(line => (line.match(/^\s*/) || [''])[0].length);
  const min = indents.length ? Math.min(...indents) : 0;
  return lines.map(line => line.slice(min)).join('\n').trim();
}

function format(html, indent) {
  return dedent(html)
    .replace(/class="project-card reveal"/g, 'class="project-card"')
    .replace(/class="skill-category reveal"/g, 'class="skill-category"')
    .replace(/<article class="project-card"/g, '<article class="project-card" data-static')
    .replace(/<div class="skill-category"/g, '<div class="skill-category" data-static')
    .replace(/\sdata-reveal="1"/g, '')
    .replace(/;?\s*--rd:\s*\d+ms;?/g, '')
    .replace(/\s*style="\s*"/g, '')
    .replace(/\n{3,}/g, '\n\n')
    .split('\n')
    .map(line => (line.trim() ? indent + line : ''))
    .join('\n')
    .trimEnd();
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function replaceBlock(html, name, indent) {
  const start = `<!-- BEGIN STATIC ${name} (generated by scripts/build-static.js) -->`;
  const end = `<!-- END STATIC ${name} -->`;
  const content = format(grids.get(name === 'PROJECTS' ? 'projects-grid' : name === 'ARCHIVE' ? 'archive-grid' : 'skills-grid').innerHTML, ' '.repeat(indent));
  const pattern = new RegExp(escapeRegExp(start) + '[\\s\\S]*?' + escapeRegExp(end));

  if (!pattern.test(html)) {
    throw new Error(`Missing static ${name} markers in index.html`);
  }

  return html.replace(pattern, () => `${start}\n${content}\n${' '.repeat(indent)}${end}`);
}

let index = fs.readFileSync(indexPath, 'utf8');
index = replaceBlock(index, 'PROJECTS', 10);
index = replaceBlock(index, 'ARCHIVE', 16);
index = replaceBlock(index, 'SKILLS', 14);
fs.writeFileSync(indexPath, index);

function absoluteUrl(value) {
  if (!value || value === '#') return '';
  return new URL(value, 'https://portfolio.fabricioporcelli.com.ar/').href;
}

function buildLlmsTxt() {
  const lines = [
    '# Fabricio Porcelli - Software Developer (AI & Data)',
    '',
    '> Portfolio of Fabricio Porcelli, a software developer focused on Python, backend, databases and AI. The site is available in English and Spanish.',
    '',
    'Site: https://portfolio.fabricioporcelli.com.ar/',
    '',
    '## Projects',
    ''
  ];

  for (const project of data.projects) {
    lines.push(`### ${project.title}`);
    const page = absoluteUrl(project.detailUrl);
    const live = absoluteUrl(project.externalUrl);
    if (page) lines.push(`Page: ${page}`);
    if (live) lines.push(`Live: ${live}`);
    if (project.githubUrl) lines.push(`GitHub: ${project.githubUrl}`);
    if (project.privateRepo) lines.push('Repository: private');
    if (project.working) lines.push('Status: in development');
    lines.push('');
    lines.push(project.description.en);
    lines.push('');
    lines.push(`Stack: ${(project.tags || []).join(', ')}`);
    lines.push('');
  }

  lines.push('## Older projects', '');

  for (const project of data.archivedProjects || []) {
    lines.push(`### ${project.title}`);
    const live = absoluteUrl(project.externalUrl);
    if (live) lines.push(`Live: ${live}`);
    if (project.githubUrl) lines.push(`GitHub: ${project.githubUrl}`);
    lines.push('');
    lines.push(project.description.en);
    lines.push('');
    lines.push(`Stack: ${(project.tags || []).join(', ')}`);
    lines.push('');
  }

  lines.push('## Skills', '');
  for (const category of data.skills.categories) {
    lines.push(`- ${category.name.en}: ${category.items.join(', ')}`);
  }
  lines.push('');
  lines.push('## Contact', '');
  lines.push('- Email: fabricioporcelli@gmail.com');
  lines.push('- GitHub: https://github.com/FabricioPorcelli');
  lines.push('- LinkedIn: https://www.linkedin.com/in/fabricio-porcelli/');
  lines.push('');

  return lines.join('\n');
}

fs.writeFileSync(path.join(root, 'llms.txt'), buildLlmsTxt());

console.log('Static fallback and llms.txt updated');
